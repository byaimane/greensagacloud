export function getStageLabelLocalized(lang: Language, progress: number): string {
  if (progress >= 1) return t(lang, 'stageMature');
  if (progress >= 0.62) return t(lang, 'stageGrowing');
  if (progress >= 0.28) return t(lang, 'stageSprout');
  return t(lang, 'stageSeed');
}
